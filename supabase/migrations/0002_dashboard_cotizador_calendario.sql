where not exists (select 1 from public.servicios);

-- ---------------------------------------------------------------------
-- 4. Cotizaciones e ítems
-- ---------------------------------------------------------------------
create table if not exists public.cotizaciones (
  id             uuid primary key default gen_random_uuid(),
  numero         integer generated by default as identity unique,
  prospecto_id   uuid references public.prospectos (id) on delete set null,
  titulo         text,
  estado         text not null default 'borrador'
                 check (estado in ('borrador', 'enviada', 'aceptada', 'rechazada')),
  fecha          date not null default current_date,
  valida_hasta   date,
  moneda         text not null default 'USD' check (moneda in ('ARS', 'USD')),
  descuento_pct  numeric(5, 2) not null default 0 check (descuento_pct between 0 and 100),
  notas          text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists public.cotizacion_items (
  id                     uuid primary key default gen_random_uuid(),
  cotizacion_id          uuid not null references public.cotizaciones (id) on delete cascade,
  servicio_id            uuid references public.servicios (id) on delete set null,
  descripcion            text not null,
  cantidad               numeric(10, 2) not null default 1,
  precio_implementacion  numeric(14, 2) not null default 0,
  precio_mensual         numeric(14, 2) not null default 0,
  orden                  integer not null default 0
);
create index if not exists cotizacion_items_cot_idx on public.cotizacion_items (cotizacion_id, orden);

-- ---------------------------------------------------------------------
-- 5. Cobros (lo que entra)
-- ---------------------------------------------------------------------
create table if not exists public.cobros (
  id             uuid primary key default gen_random_uuid(),
  fecha          date not null default current_date,
  monto          numeric(14, 2) not null check (monto >= 0),
  moneda         text not null default 'USD' check (moneda in ('ARS', 'USD')),
  concepto       text not null default 'anticipo'
                 check (concepto in ('anticipo', 'saldo', 'abono', 'extra')),
  prospecto_id   uuid references public.prospectos (id) on delete set null,
  cotizacion_id  uuid references public.cotizaciones (id) on delete set null,
  notas          text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists cobros_fecha_idx on public.cobros (fecha);

-- ---------------------------------------------------------------------
-- 6. Costos (lo que cuesta sostener el estudio)
-- ---------------------------------------------------------------------
create table if not exists public.costos (
  id          uuid primary key default gen_random_uuid(),
  nombre      text not null,
  categoria   text not null default 'apps'
              check (categoria in ('apps', 'ia', 'hosting', 'dominios', 'fees', 'adquisicion')),
  monto       numeric(14, 2) not null check (monto >= 0),
  moneda      text not null default 'USD' check (moneda in ('ARS', 'USD')),
  frecuencia  text not null default 'mensual' check (frecuencia in ('mensual', 'anual', 'unico')),
  desde       date not null default current_date,
  hasta       date,
  notas       text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 7. Reuniones (calendario)
-- ---------------------------------------------------------------------
create table if not exists public.reuniones (
  id             uuid primary key default gen_random_uuid(),
  titulo         text not null,
  inicio         timestamptz not null,
  duracion_min   integer not null default 60 check (duracion_min > 0),
  prospecto_id   uuid references public.prospectos (id) on delete set null,
  lugar_o_link   text,
  responsable    text,
  notas          text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists reuniones_inicio_idx on public.reuniones (inicio);

-- ---------------------------------------------------------------------
-- 8. updated_at automático + seguridad (RLS: solo miembros)
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['ajustes', 'servicios', 'cotizaciones', 'cobros', 'costos', 'reuniones'] loop
    execute format('drop trigger if exists %1$s_updated_at on public.%1$s', t);
    execute format('create trigger %1$s_updated_at before update on public.%1$s
                    for each row execute function public.set_updated_at()', t);
  end loop;

  foreach t in array array['ajustes', 'servicios', 'cotizaciones', 'cotizacion_items', 'cobros', 'costos', 'reuniones'] loop
    execute format('alter table public.%s enable row level security', t);
    execute format('drop policy if exists "%1$s_miembros" on public.%1$s', t);
    execute format('create policy "%1$s_miembros" on public.%1$s for all to authenticated
                    using (public.es_miembro()) with check (public.es_miembro())', t);
  end loop;
end $$;
