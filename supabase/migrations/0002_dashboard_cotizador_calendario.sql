-- ---------------------------------------------------------------------
-- 1. Pipeline: nuevas etapas después de "cerrado"
-- ---------------------------------------------------------------------
alter table public.prospectos drop constraint if exists prospectos_etapa_check;
alter table public.prospectos add constraint prospectos_etapa_check
  check (etapa in ('contacto', 'reunion', 'demo', 'propuesta',
                   'cerrado', 'implementacion', 'mantenimiento', 'perdido'));

-- ---------------------------------------------------------------------
-- 2. Ajustes (una sola fila): tipo de cambio para pasar ARS a USD
-- ---------------------------------------------------------------------
create table if not exists public.ajustes (
  id               boolean primary key default true check (id),
  tipo_cambio_usd  numeric(14, 2),          -- cuántos ARS vale 1 USD
  updated_at       timestamptz not null default now()
);
insert into public.ajustes (id) values (true) on conflict (id) do nothing;

-- ---------------------------------------------------------------------
-- 3. Servicios: catálogo con precios (en USD)
-- ---------------------------------------------------------------------
create table if not exists public.servicios (
  id                     uuid primary key default gen_random_uuid(),
  nombre                 text not null,
  descripcion            text,
  precio_implementacion  numeric(14, 2) not null default 0,
  precio_mensual         numeric(14, 2) not null default 0,
  activo                 boolean not null default true,
  orden                  integer not null default 0,
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now()
);

